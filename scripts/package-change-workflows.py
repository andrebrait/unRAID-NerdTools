#!/usr/bin/env python3
"""Regenerate per-package workflows from source locks; --check reports drift.

Run: python3 scripts/package-change-workflows.py [--check]
Generated wrappers deliberately avoid GitHub paths filters: semantic selection
inside the reusable workflow sees the complete diff, including >300 files.
"""

import argparse
import importlib.util
from pathlib import Path


SPEC = importlib.util.spec_from_file_location("package_change", Path(__file__).with_name("package-change.py"))
changes = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(changes)
HEADER = "# Generated by scripts/package-change-workflows.py; do not edit.\n"


def wrapper(name):
    return HEADER + f"""name: Native package — {name}

on:
  pull_request:
  push:
    branches: [master, main]
  workflow_dispatch:

permissions:
  contents: read

jobs:
  build:
    uses: ./.github/workflows/package-build.yml
    with:
      package: "{name}"
"""


def generate(repo, check=False):
    repo = Path(repo)
    packages = changes.working_packages(repo)
    if "build" in packages:
        raise ValueError("Package name 'build' collides with the reusable workflow")
    folder = repo / ".github/workflows"
    expected = {f"package-{name}.yml": wrapper(name) for name in sorted(packages)}
    existing = {path.name: path for path in folder.glob("package-*.yml") if path.name != "package-build.yml"}
    stale = set(existing) - set(expected)
    # Only generated wrappers are ours to remove; unrelated workflow files survive.
    stale = {name for name in stale if existing[name].read_text().startswith(HEADER)}
    mismatched = {name for name, text in expected.items()
                  if not (folder / name).exists() or (folder / name).read_text() != text}
    if check:
        for name in sorted(stale | mismatched):
            print(f"Workflow drift: .github/workflows/{name}")
        return not (stale or mismatched)
    folder.mkdir(parents=True, exist_ok=True)
    for name in sorted(stale):
        existing[name].unlink()
    for name in sorted(mismatched):
        (folder / name).write_text(expected[name])
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    raise SystemExit(0 if generate(args.repo, args.check) else 1)


if __name__ == "__main__":
    main()
