#!/usr/bin/env python3
"""Regenerate per-package workflows and the catalog package jobs from source locks; --check reports drift.

Run: python3 scripts/package-change-workflows.py [--check]
Generated wrappers deliberately avoid GitHub paths filters: semantic selection
inside the reusable workflow sees the complete diff, including >300 files.
"""

import argparse
import importlib.util
from pathlib import Path


SPEC = importlib.util.spec_from_file_location("package_change", Path(__file__).with_name("package-change.py"))
changes = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(changes)
HEADER = "# Generated by scripts/package-change-workflows.py; do not edit.\n"
CATALOG = ".github/workflows/build-packages.yml"
BEGIN = "  # BEGIN generated package jobs (scripts/package-change-workflows.py); do not edit.\n"
END = "  # END generated package jobs\n"


def wrapper(name):
    return HEADER + f"""name: Native package — {name}

on:
  pull_request:
  push:
    branches: [master, main]
  workflow_dispatch:

permissions:
  contents: read

jobs:
  build:
    uses: ./.github/workflows/package-build.yml
    with:
      package: "{name}"
"""


def catalog_dependencies(packages):
    """Catalog packages each catalog package must wait for; build-only helpers are compiled inside
    their dependents' jobs, so look through them."""
    def direct(name):
        found = set()
        for dep in packages[name]["dependencies"] + packages[name]["build_dependencies"]:
            found |= {dep} if packages[dep].get("catalog", True) else direct(dep)
        return found
    return {name: sorted(direct(name)) for name in sorted(packages) if packages[name].get("catalog", True)}


def catalog_jobs(packages):
    """One job per catalog package, waiting only for its own catalog dependencies. A job runs when the
    plan lists its package; a dependency that is skipped is unchanged and comes from the previous release."""
    graph = catalog_dependencies(packages)
    jobs = [BEGIN]
    for name, deps in graph.items():
        needs = ", ".join(["package-list"] + [f"package-{dep}" for dep in deps])
        same_run = " || ".join(f"contains(needs.package-list.outputs.names, '\"{dep}\"')" for dep in deps)
        jobs.append(f"""  package-{name}:
    needs: [{needs}]
    if: ${{{{ !cancelled() && !contains(needs.*.result, 'failure') && !contains(needs.*.result, 'cancelled') && contains(needs.package-list.outputs.names, '"{name}"') }}}}
    uses: ./.github/workflows/package-build.yml
    with:
      package: "{name}"
      retain-artifact: true
      same-run-dependencies: {f"${{{{ {same_run} }}}}" if deps else "false"}
      builds: ${{{{ needs.package-list.outputs.builds }}}}
      reuse: ${{{{ needs.package-list.outputs.reuse }}}}
      reuse-tag: ${{{{ needs.package-list.outputs.tag }}}}

""")
    jobs.append(f"""  # Fails when any package job failed or was cancelled; skipped jobs are carried over.
  packages:
    needs: [package-list, {", ".join(f"package-{name}" for name in graph)}]
    if: ${{{{ !cancelled() && needs.package-list.result == 'success' }}}}
    runs-on: ubuntu-24.04
    steps:
      - name: Require every planned package job to succeed
        env:
          RESULTS: ${{{{ toJSON(needs.*.result) }}}}
        run: echo "$RESULTS"; ! grep -qE 'failure|cancelled' <<<"$RESULTS"
""")
    jobs.append(END)
    return "".join(jobs)


def generate(repo, check=False):
    repo = Path(repo)
    packages = changes.working_packages(repo)
    if {"build", "list"} & set(packages):
        raise ValueError("Package names 'build' and 'list' collide with workflow files and jobs")
    folder = repo / ".github/workflows"
    expected = {f"package-{name}.yml": wrapper(name) for name in sorted(packages)}
    existing = {path.name: path for path in folder.glob("package-*.yml") if path.name != "package-build.yml"}
    stale = set(existing) - set(expected)
    # Only generated wrappers are ours to remove; unrelated workflow files survive.
    stale = {name for name in stale if existing[name].read_text().startswith(HEADER)}
    mismatched = {name for name, text in expected.items()
                  if not (folder / name).exists() or (folder / name).read_text() != text}
    catalog = repo / CATALOG
    text = catalog.read_text()
    start, end = text.index(BEGIN), text.index(END) + len(END)
    expected_catalog = text[:start] + catalog_jobs(packages) + text[end:]
    if check:
        for name in sorted(stale | mismatched):
            print(f"Workflow drift: .github/workflows/{name}")
        if text != expected_catalog:
            print(f"Workflow drift: {CATALOG}")
        return not (stale or mismatched) and text == expected_catalog
    folder.mkdir(parents=True, exist_ok=True)
    for name in sorted(stale):
        existing[name].unlink()
    for name in sorted(mismatched):
        (folder / name).write_text(expected[name])
    catalog.write_text(expected_catalog)
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    raise SystemExit(0 if generate(args.repo, args.check) else 1)


if __name__ == "__main__":
    main()
